// stimulus-transaction-structure, Property 4: Every total declaration over the four members
// renders, one overwrite per owning role (task 4.5, C3).
//
// THE ORACLE IS A SEPARATE PARSE OF THE RENDERED TEXT
//   This file never imports `renderStimulusFunction` (it is not exported). It regexes the
//   rendered `ece_stimulus` body for the two shapes C3 documents as "one overwrite line per
//   owning-role port": the replication-operator line an `enable` or `strobe` role emits
//   (`v[hi:lo] = {w{(step % N) op 0}};`) and the `v_hold` copy a `hold` role emits
//   (`v[hi:lo] = v_hold[hi:lo];`). It then counts, per input port's own `packedPortSlices` slice,
//   how many such lines overwrite exactly that slice - the role is read from the generated
//   `RoleDeclaration` this file built, never from the rendered text, so the check cannot
//   congratulate itself by reading back what it already knows. This generalizes
//   `rendered-stimulus-layout.property.test.ts`'s enable-vs-data role-fidelity check (which only
//   had `enable` and `data` to distinguish) to all three owning roles the widened vocabulary adds.
//
// WHY A RENDERER REFUSAL IS SKIPPED RATHER THAN FAILED
//   `arbModuleInterface()`'s identifier generator avoids only a small keyword set, not the
//   renderer's full `VERILOG_KEYWORDS` list, so an occasional reserved-keyword draw is a
//   legitimate refusal rather than a defect in this property - the same reasoning
//   `rendered-stimulus-layout.property.test.ts` and `rendered-stimulus-determinism.property.test.ts`
//   already rely on. Non-vacuity is checked instead by requiring at least one draw to be accepted.
//
// THE ROLE ARBITRARY
//   `fc.constantFrom(...INPUT_ROLES)`, imported from the real `consensus-harness.ts` module, so a
//   future fifth vocabulary member is generated by this test with no edit here.
//
// Validates: Requirements 1.8

import fc from 'fast-check';
import { describe, expect, it } from 'vitest';

import { makeTimingContract, type ModuleInterface, type TimingContract } from '@app/core';
import {
  INPUT_ROLES,
  packedPortSlices,
  renderConsensusHarness,
  type ConsensusHarnessRequest,
  type InputRole,
  type RoleDeclaration,
} from '@app/tools';

import { ASCII_IDENT_CHARS, stringFromChars } from './generators/chars.js';
import { arbModuleInterface } from './interface-header-arbitraries.js';
import { propertyParameters } from './property.js';

const PROPERTY =
  'stimulus-transaction-structure, Property 4: Every total declaration over the four members ' +
  'renders, one overwrite per owning role';

/** No SystemVerilog-2017 keyword begins with this, so a drawn nonce never needs a retry. */
const NONCE_PREFIX = 'zzro';

function nonceArbitrary(): fc.Arbitrary<string> {
  return stringFromChars(ASCII_IDENT_CHARS, 0, 6).map((suffix) => `${NONCE_PREFIX}${suffix}`);
}

/** One `registered` entry per output port of `moduleInterface`, built directly from its own ports. */
function allRegisteredTiming(moduleInterface: ModuleInterface): TimingContract {
  const entries = moduleInterface.ports
    .filter((port) => port.direction === 'output')
    .map((port) => ({ portName: port.name, timing: 'registered' as const }));
  const built = makeTimingContract(moduleInterface, entries);
  if (!built.ok) {
    throw new Error(`fixture defect building the timing contract: ${built.error.code}`);
  }
  return built.value;
}

/** A Total_Role_Declaration over `moduleInterface`'s input ports: one independently drawn member of the full vocabulary per port, in declared order. */
function arbRolesFor(moduleInterface: ModuleInterface): fc.Arbitrary<RoleDeclaration> {
  const inputPorts = moduleInterface.ports.filter((port) => port.direction === 'input');
  return fc
    .array(fc.constantFrom(...INPUT_ROLES), {
      minLength: inputPorts.length,
      maxLength: inputPorts.length,
    })
    .map((drawnRoles) =>
      inputPorts.map((port, index) => ({
        portName: port.name,
        role: drawnRoles[index] as InputRole,
      })),
    );
}

function arbRequestScenario(): fc.Arbitrary<{
  readonly moduleInterface: ModuleInterface;
  readonly roles: RoleDeclaration;
  readonly request: ConsensusHarnessRequest;
}> {
  return arbModuleInterface().chain((moduleInterface) =>
    fc
      .record({
        roles: arbRolesFor(moduleInterface),
        nonce: nonceArbitrary(),
        watchdogBudgetNs: fc.integer({ min: 1, max: 2_000_000 }),
        sampleBudget: fc.integer({ min: 1, max: 64 }),
      })
      .map(({ roles, nonce, watchdogBudgetNs, sampleBudget }) => ({
        moduleInterface,
        roles,
        request: {
          moduleInterface,
          timingContract: allRegisteredTiming(moduleInterface),
          nonce,
          watchdogBudgetNs,
          sampleBudget,
          roles,
        },
      })),
  );
}

// ---------------------------------------------------------------------------
// The oracle: an independent parse of every role-owned overwrite line
// ---------------------------------------------------------------------------

/** `enable`'s and `strobe`'s shared shape: one common value over the whole slice, keyed on `step`. */
const LEVEL_OVERWRITE_LINE = /^ {4}v\[(\d+):(\d+)] = \{\d+\{\(step % \d+\) (?:!=|==) 0\}\};$/;
/** `hold`'s shape: the port's own slice of the shared held bundle. */
const HOLD_OVERWRITE_LINE = /^ {4}v\[(\d+):(\d+)] = v_hold\[\d+:\d+\];$/;

/** Every `v[hi:lo]` range a role-owned overwrite line targets, read with no notion of which role produced it. */
function overwrittenRanges(renderedContents: string): readonly { high: number; low: number }[] {
  const ranges: { high: number; low: number }[] = [];
  for (const line of renderedContents.split('\n')) {
    const match = LEVEL_OVERWRITE_LINE.exec(line) ?? HOLD_OVERWRITE_LINE.exec(line);
    if (match !== null) {
      ranges.push({ high: Number(match[1]), low: Number(match[2]) });
    }
  }
  return ranges;
}

/**
 * Assert Property 4 over one rendered harness: each input port's own `packedPortSlices` slice
 * carries exactly one role-owned overwrite line when `roles` names it `enable`, `strobe`, or
 * `hold`, and none when `roles` names it `data`.
 */
function assertOneOverwritePerOwningRole(
  inputPorts: readonly { readonly name: string; readonly width: number }[],
  roles: RoleDeclaration,
  renderedContents: string,
): void {
  const ranges = overwrittenRanges(renderedContents);
  for (const slice of packedPortSlices(inputPorts)) {
    const role = roles.find((entry) => entry.portName === slice.name)?.role;
    if (role === undefined) {
      throw new Error(`fixture defect: roles carries no entry for port "${slice.name}"`);
    }
    const matchingRanges = ranges.filter(
      (range) => range.low === slice.low && range.high === slice.high,
    );
    const expectedOverwriteCount = role === 'data' ? 0 : 1;
    expect(matchingRanges.length, `port "${slice.name}" (role "${role}")`).toBe(
      expectedOverwriteCount,
    );
  }
}

describe(PROPERTY, () => {
  it(
    "renders exactly one overwrite line over each enable/strobe/hold-role port's own slice and " +
      "none over a data-role port's slice, for a widely varied Declared_Interface and role draw",
    () => {
      let acceptedAtLeastOnce = false;

      fc.assert(
        fc.property(arbRequestScenario(), ({ moduleInterface, roles, request }) => {
          const rendered = renderConsensusHarness(request);
          if (!rendered.ok) {
            return;
          }
          acceptedAtLeastOnce = true;
          const inputPorts = moduleInterface.ports.filter((port) => port.direction === 'input');
          assertOneOverwritePerOwningRole(inputPorts, roles, rendered.value.contents);
        }),
        propertyParameters(),
      );

      expect(acceptedAtLeastOnce, 'no draw was accepted by the renderer').toBe(true);
    },
  );
});
